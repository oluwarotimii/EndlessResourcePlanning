// Fails when the handover documents drift from the code.
//  1. docs/SCREEN-STATUS.md is generated from the screen registry, the built screens and docs/screen-status-notes.json.
//  2. docs/TENANT-CONFIG.md must mention every setting in packages/tenant-config/tenant.json.
// Run `node scripts/check-docs.mjs --write` to regenerate SCREEN-STATUS.md after adding or building a screen.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const read = (p) => readFileSync(join(root, p), "utf8");
const write = process.argv.includes("--write");
const problems = [];

// ---- 1. screen status
const screens = JSON.parse(read("packages/permissions/src/data/screens.json"));
const built = new Set([
  ...read("apps/web/src/screens/registry.ts").matchAll(/^\s+([A-Z]+\d+):\s*lazy/gm),
  ...read("apps/web/src/screens/registry.ts").matchAll(/^\s+([A-Z]+\d+):\s*true/gm),
].map((m) => m[1]));
const notes = JSON.parse(read("docs/screen-status-notes.json"));
const status = (s) => (built.has(s.id) ? "Built" : notes[s.id] ? "Partly built" : "Placeholder");
const esc = (v) => String(v).replaceAll("|", "/");
const row = (s) => `| ${s.id} | ${esc(s.title)} | ${esc(s.area)} | ${esc(s.roles.length > 4 ? `${s.roles.length} roles` : s.roles.join(", "))} | ${s.scope} | ${s.sprint} | ${status(s)} | ${esc(notes[s.id] ?? "")} |`;
const mvp = screens.filter((s) => s.scope === "MVP");
const count = (list, st) => list.filter((s) => status(s) === st).length;
const table = (list) => ["| ID | Screen | Area | Roles | Scope | Sprint | Status | Notes |", "| --- | --- | --- | --- | --- | --- | --- | --- |", ...list.map(row)].join("\n");
const generated = `# Screen status

GENERATED by \`node scripts/check-docs.mjs --write\` from the screen registry (\`apps/web/src/screens/registry.ts\`), \`docs/screen-status-notes.json\` and the inventory. Do not edit by hand; edit the notes file.

**MVP (29 screens):** ${count(mvp, "Built")} built, ${count(mvp, "Partly built")} partly built, ${count(mvp, "Placeholder")} placeholder.
**All 93 screens:** ${count(screens, "Built")} built, ${count(screens, "Partly built")} partly built, ${count(screens, "Placeholder")} placeholder.

## MVP screens

${table(mvp)}

## Later screens

${table(screens.filter((s) => s.scope !== "MVP"))}
`;
if (write) { writeFileSync(join(root, "docs/SCREEN-STATUS.md"), generated); console.log("check-docs: wrote docs/SCREEN-STATUS.md"); }
else {
  let current = "";
  try { current = read("docs/SCREEN-STATUS.md"); } catch { /* missing */ }
  if (current !== generated) problems.push("docs/SCREEN-STATUS.md is out of date. Run: node scripts/check-docs.mjs --write");
}

// ---- 2. tenant.json settings are documented
// Maps keyed by category or product name are one setting each (their keys are data, not settings).
const MAPS = new Set(["byCategory", "byProduct"]);
const flat = (o, prefix = "") => Object.entries(o).flatMap(([k, v]) => (v && typeof v === "object" && !Array.isArray(v) && !MAPS.has(k) ? flat(v, `${prefix}${k}.`) : [`${prefix}${k}`]));
const doc = read("docs/TENANT-CONFIG.md");
for (const key of flat(JSON.parse(read("packages/tenant-config/tenant.json")))) {
  if (!doc.includes(`\`${key}\``)) problems.push(`docs/TENANT-CONFIG.md does not document tenant.json setting \`${key}\``);
}

// ---- 3. every kind of approval is described in docs/APPROVAL-ROUTING.md
const kindsMatch = read("packages/api-contract/src/index.ts").match(/ApprovalKind = z\.enum\(\[([^\]]*)\]\)/);
const routingDoc = read("docs/APPROVAL-ROUTING.md");
for (const kind of (kindsMatch?.[1] ?? "").match(/"([a-z_]+)"/g)?.map((k) => k.replaceAll('"', "")) ?? []) {
  if (!routingDoc.includes(`\`${kind}\``)) problems.push(`docs/APPROVAL-ROUTING.md does not describe the approval kind \`${kind}\``);
}

// ---- 4. every approval kind and queued action is mapped to ERPNext (docs/ERPNEXT-MAPPING.md)
const mapping = read("docs/ERPNEXT-MAPPING.md");
const queueMatch = read("packages/offline/src/types.ts").match(/QueueItemType\s*=\s*([^;]+);/);
const queued = (queueMatch?.[1] ?? "").match(/"([a-z.]+)"/g)?.map((k) => k.replaceAll('"', "")) ?? [];
const approvalKinds = (kindsMatch?.[1] ?? "").match(/"([a-z_]+)"/g)?.map((k) => k.replaceAll('"', "")) ?? [];
for (const name of [...queued, ...approvalKinds]) {
  if (!mapping.includes(`\`${name}\``)) problems.push(`docs/ERPNEXT-MAPPING.md does not map \`${name}\` to ERPNext`);
}

// ---- 5. every API path the mock exposes is in the Frappe app spec (docs/FRAPPE-APP-SPEC.md)
const serverSrc = read("apps/mock-server/src/server.ts");
const staticPaths = [...serverSrc.matchAll(/pathname === "(\/api\/[^"]+)"/g)].map((m) => m[1]);
const dynamicPaths = [...serverSrc.matchAll(/match\(\/\^(\\\/api[^$]*)\$\/\)/g)].map((m) => m[1].replaceAll("\\/", "/").replace("([^/]+)", ":id"));
const spec = read("docs/FRAPPE-APP-SPEC.md");
for (const path of [...staticPaths, ...dynamicPaths]) {
  if (!spec.includes(`\`${path}\``)) problems.push(`docs/FRAPPE-APP-SPEC.md does not list the API path \`${path}\``);
}

if (problems.length) { console.error("Documentation is out of sync:\n- " + problems.join("\n- ")); process.exit(1); }
console.log(`check-docs: screen status and tenant settings are documented`);
