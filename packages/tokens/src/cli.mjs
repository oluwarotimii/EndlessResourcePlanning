import { writeFileSync, mkdirSync, readdirSync, readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { buildThemeCss } from "./build.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const dir = join(here, "themes");
const css = readdirSync(dir)
  .filter((f) => f.endsWith(".json"))
  .sort()
  .map((f) => buildThemeCss(JSON.parse(readFileSync(join(dir, f), "utf8"))))
  .join("\n\n");
mkdirSync(join(here, "..", "dist"), { recursive: true });
writeFileSync(join(here, "..", "dist", "tokens.css"), `/* GENERATED by packages/tokens. Do not edit. */\n${css}\n`);
console.log("tokens: wrote dist/tokens.css");
